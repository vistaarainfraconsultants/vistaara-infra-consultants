"""
Refresh content.js — the list of photos, videos, projects and careers the website shows.

Run this after adding, renaming or removing files in images/, projects/ or careers/:

    python tools/update-content.py

(On GitHub the workflow in .github/workflows/update-content.yml runs it for you.)
Works with any host: upload the updated content.js together with your new files.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FOLDERS = ["images", "projects", "careers"]
JSON_NAMES = {"project.json", "job.json"}

files, data = [], {}
for folder in FOLDERS:
    base = ROOT / folder
    if not base.is_dir():
        continue
    # sort by the text path so Windows and the GitHub Action give the same order
    for path in sorted(base.rglob("*"), key=lambda p: p.relative_to(ROOT).as_posix()):
        if not path.is_file() or path.name.startswith("."):
            continue
        rel = path.relative_to(ROOT).as_posix()
        files.append(rel)
        if path.name.lower() in JSON_NAMES:
            text = path.read_text(encoding="utf-8-sig").strip()
            if not text:
                continue
            try:
                data[rel] = json.loads(text)
            except json.JSONDecodeError as err:
                print(f"WARNING: {rel} is not valid JSON ({err}) — it will be skipped on the site.")

# no timestamp: content.js only changes when the files really change (avoids needless commits)
content = {"files": files, "data": data}
blob = json.dumps(content, ensure_ascii=False, indent=1).replace("</", "<\\/")
(ROOT / "content.js").write_text(
    "/* Generated by tools/update-content.py — do not edit by hand. */\n"
    f"window.VISTAARA_CONTENT = {blob};\n",
    encoding="utf-8",
)
print(f"content.js updated: {len(files)} files, {len(data)} project/career entries.")
